# Python Data Types
# =================

# Integer (int)
# Definition: An integer is a whole number without a decimal point.
# It can be positive, negative, or zero.
a = 10
print(type(a))


# Float (float)
# Definition: A float is a number that contains a decimal value.
# It is used when we need to work with fractional or decimal numbers.
b = 3.14
print(type(b))


# String (str)
# Definition: A string is a sequence of characters used to store text.
# It is written inside single or double quotes.
c = "Hello"
print(type(c))


# Boolean (bool)
# Definition: A Boolean represents a logical value.
# It can have only two values: True or False.
d = True
print(type(d))


# List (list)
# Definition: A list is an ordered and mutable collection of elements.
# We can add, remove, or modify elements in a list.
e = [1, 2, 3, 4]
print(type(e))


# Tuple (tuple)
# Definition: A tuple is an ordered and immutable collection of elements.
# Once created, its elements cannot be changed.
f = (1, 2, 3, 4)
print(type(f))


# Set (set)
# Definition: A set is an unordered collection of unique elements.
# It automatically removes duplicate values.
g = {1, 2, 3, 4}
print(type(g))


# Dictionary (dict)
# Definition: A dictionary stores data in key-value pairs.
# Each key is used to access its corresponding value.
h = {"name": "Alice", "age": 25}
print(type(h))